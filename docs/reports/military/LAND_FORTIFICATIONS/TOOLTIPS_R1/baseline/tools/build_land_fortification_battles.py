"""Generate local fortification battle conditions from the canonical vanilla.

No global unit or commander modifier is used. A fortified defending side uses
a local stance, with native pursuit/panicked/controlled retreat variants. The
native condition database is preserved outside the eligible fortified battle.
Default is read-only; --write exports only this lot's generated files.
"""
from copy import deepcopy
from decimal import Decimal
from pathlib import Path
import argparse
import hashlib
import json

from validate_diplomacy_ottoman_1776 import parse, walk, Node, normalized

ROOT = Path(__file__).resolve().parents[1]
GAME = Path('C:/Games/Victoria 3/game')
REPORT = ROOT / 'docs/reports/military/LAND_FORTIFICATIONS'
BASEFILE = 'common/battle_conditions/00_battle_conditions.txt'
NEWFILE = 'common/battle_conditions/1776_land_fortifications.txt'
TRIGFILE = 'common/scripted_triggers/1776_land_fortifications.txt'
VALUEFILE = 'common/script_values/1776_land_fortifications.txt'
NET = 'aor1776_land_fort_net_protection'
ENGINEERS = 'aor1776_land_fort_enemy_engineers'
GROSS = 'aor1776_land_fort_gross_protection'
ELIGIBLE = 'aor1776_land_fortification_battle_eligible'
STRENGTH = 'state_aor1776_land_fortification_strength_add'
URGENT = ['pursuit', 'panicked_retreat', 'controlled_retreat']
HEADER = '# Generated by tools/build_land_fortification_battles.py from canonical vanilla.\n'


def node(key, value, op='='):
    return Node(key, op, value, 0, 0)


def parsed(text):
    return parse(text)[0]


def fort_key(kind, strength):
    return f'battle_condition_aor1776_land_fort_{kind}_{strength:02d}'


def points_key(kind, points):
    # Retain all pre-engineer keys (multiples of five) for existing saves.
    if points % 5 == 0:
        return fort_key(kind, points // 5)
    return f'battle_condition_aor1776_land_fort_{kind}_reduced_{points:02d}'


def class_key(kind):
    return f'aor1776_land_battle_is_{kind}'


def can_key(kind):
    return f'aor1776_land_battle_native_can_{kind}'


def render(nodes, depth=0):
    lines = []
    for n in nodes:
        pad = '\t' * depth
        if isinstance(n.value, list):
            lines.append(f'{pad}{n.key} {n.op} {{')
            lines.extend(render(n.value, depth + 1))
            lines.append(pad + '}')
        else:
            lines.append(f'{pad}{n.key} {n.op} {n.value}')
    return lines


def text_of(nodes):
    return HEADER + '\n\n'.join('\n'.join(render([n])) for n in nodes) + '\n'


def expand_urgent_references(nodes):
    for n in walk(nodes):
        if n.key == 'has_battle_condition' and isinstance(n.value, str):
            for kind in URGENT:
                if n.value == 'battle_condition_' + kind:
                    n.key = class_key(kind)
                    n.value = 'yes'
                    break


def band(points):
    return node(NET, str(points))


def protection(strength):
    return {'unit_provinces_lost_mult': -min(Decimal('.05') * strength, Decimal('.75')),
            'battle_casualties_mult': Decimal('-.05') * strength,
            'unit_army_defense_mult': Decimal('.05') * strength}


def with_protection(base, strength):
    result = deepcopy(base)
    extra = protection(strength)
    for n in result:
        if n.key in extra:
            n.value = str(Decimal(n.value) + extra.pop(n.key))
    result.extend(node(key, str(value)) for key, value in extra.items())
    return result


def build():
    baseline = json.loads((REPORT / 'BASELINE.json').read_text(encoding='utf-8'))
    data = (GAME / BASEFILE).read_bytes()
    assert hashlib.sha256(data).hexdigest() == baseline['canonical_game'][BASEFILE], 'Canonical battle database changed: audit the new version first.'
    original = parse(data.decode('utf-8-sig'))
    originals = {n.key: n for n in original}
    assert {n.key for n in original if n.children('instant_switch')} == {'battle_condition_' + x for x in URGENT}
    helpers = [parsed(f'''{ELIGIBLE} = {{
        scope:is_advancing_side = no
        exists = country
        province = {{ owner = prev.country controller = prev.country }}
        state = {{
            owner = prev.country
            is_coastal = no
            has_building = building_aor1776_land_fortification
            modifier:{STRENGTH} >= 0.5
        }}
        {NET} > 0
    }}''')]
    for kind in URGENT:
        members = [node('has_battle_condition', 'battle_condition_' + kind)]
        members.extend(node('has_battle_condition', points_key(kind, i)) for i in range(1, 76))
        helpers.append(node(class_key(kind), [node('OR', members)]))
    helpers.append(node('aor1776_land_battle_is_urgent', [node('OR', [node(class_key(kind), 'yes') for kind in URGENT])]))
    helpers.append(node('aor1776_land_battle_is_fortified_stance', [node('OR', [
        node('has_battle_condition', points_key('defense', i)) for i in range(1, 76)])]))
    for kind in URGENT:
        raw = deepcopy(originals['battle_condition_' + kind].children('instant_switch')[0].children())
        expand_urgent_references(raw)
        helpers.append(node(can_key(kind), raw))

    # Override the native file once, preserving every normal modifier and weight.
    # The native emergency classes recognize the fortified equivalents too.
    standard = deepcopy(original)
    expand_urgent_references(standard)
    for n in standard:
        possible = n.children('possible')
        if possible:
            possible[0].value.insert(0, node('NOT', [node(ELIGIBLE, 'yes')]))
        if n.key in {'battle_condition_' + x for x in URGENT}:
            kind = n.key.removeprefix('battle_condition_')
            switch = n.children('instant_switch')[0]
            switch.value = [node('NOT', [node(ELIGIBLE, 'yes')]),
                            node('NOT', [node('has_battle_condition', n.key)]),
                            node('OR', [node(can_key(kind), 'yes'), node(class_key(kind), 'yes')])]

    forts = []
    for points in range(1, 76):
        strength = Decimal(points) / 5
        key = points_key('defense', points)
        available = [node(ELIGIBLE, 'yes'), band(points)]
        safe_switch = available + [
            node('NOT', [node('has_battle_condition', key)]),
            node('NOT', [node('aor1776_land_battle_is_urgent', 'yes')]),
            node('NOR', [node(can_key(kind), 'yes') for kind in URGENT]),
        ]
        forts.append(node(key, [
            node('icon', '"gfx/interface/icons/battle_conditions/battle_condition_dug_in.dds"'),
            node('modifier', with_protection([], strength)),
            node('possible', deepcopy(available)), node('instant_switch', deepcopy(safe_switch)),
            node('weight', '1'),
        ]))
        for kind in URGENT:
            source = originals['battle_condition_' + kind]
            weight = deepcopy(source.children('weight')[0])
            expand_urgent_references([weight])
            forts.append(node(points_key(kind, points), [
                node('icon', source.one('icon')),
                node('modifier', with_protection(source.children('modifier')[0].children(), strength)),
                node('instant_switch', deepcopy(available) + [
                    node('NOT', [node('has_battle_condition', points_key(kind, points))]),
                    node('OR', [node(can_key(kind), 'yes'), node(class_key(kind), 'yes')]),
                ]), weight,
            ]))
    # A demolition, empty garrison or occupation cannot leave a fort bonus on a
    # normal battle stance. Emergency stances remap to their native equivalent.
    forts.append(parsed('''battle_condition_aor1776_land_fort_abandoned = {
        icon = "gfx/interface/icons/battle_conditions/battle_condition_dug_in.dds"
        modifier = { }
        instant_switch = {
            NOT = { aor1776_land_fortification_battle_eligible = yes }
            aor1776_land_battle_is_fortified_stance = yes
        }
        weight = 1
    }'''))
    values = parse(f'''{GROSS} = {{
        value = 0
        state = {{ add = modifier:{STRENGTH} }}
        round = yes
        min = 0
        max = 15
        multiply = 5
    }}
    {ENGINEERS} = {{
        value = 0
        battle = {{
            every_combat_unit = {{
                limit = {{
                    has_unit_type = unit_type:combat_unit_type_aor1776_engineer_corps
                    owner = {{ has_war_with = prev.prev.prev.country }}
                }}
                add = {{ value = manpower divide = 1000 }}
            }}
        }}
        min = 0
        max = 75
    }}
    {NET} = {{
        value = {GROSS}
        subtract = {ENGINEERS}
        round = yes
        min = 0
        max = 75
    }}''')
    outputs = {BASEFILE: text_of(standard), NEWFILE: text_of(forts), TRIGFILE: text_of(helpers), VALUEFILE: text_of(values)}
    return outputs, originals, standard, forts


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--write', action='store_true')
    args = ap.parse_args()
    outputs, original, standard, forts = build()
    record = REPORT / 'BATTLE_GENERATION.json'
    previous = json.loads(record.read_text()) if record.exists() else {}
    for rel, text in outputs.items():
        dest = ROOT / rel
        expected = text.encode('utf-8')
        if args.write and (not dest.exists() or dest.read_bytes() != expected):
            if dest.exists():
                assert hashlib.sha256(dest.read_bytes()).hexdigest() == previous.get('files', {}).get(rel), 'Concurrent generated-file edit: ' + rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(expected)
        assert dest.read_bytes() == expected, 'Generated battle output differs: ' + rel
    evidence = dict(native_conditions=len(original), local_conditions=len(forts),
                    strength_bands=15, net_protection_bands=75, native_emergency_classes=URGENT,
                    files={rel: hashlib.sha256((ROOT / rel).read_bytes()).hexdigest() for rel in outputs},
                    canonical_source_sha256=hashlib.sha256((GAME / BASEFILE).read_bytes()).hexdigest(),
                    runtime='NOT_RUN')
    if args.write: record.write_text(json.dumps(evidence, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(evidence, indent=2))


if __name__ == '__main__':
    main()
