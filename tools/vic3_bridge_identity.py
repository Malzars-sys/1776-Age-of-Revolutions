"""Render scope-native diagnostic identity from effective mod/native definitions.

Emits an apply_patch patch on stdout; never rewrites runtime files itself.
No graphical text/GUI localization data functions are used by the generated code.
"""
from pathlib import Path
import json
import re
import sys
import infrastructure_landscape_prototype as prototype
import validate_diplomacy_ottoman_1776 as cw

TARGET = 'common/scripted_effects/z_aor1776_bridge_identity.txt'


def definitions(folder, pattern):
    effective = {p.relative_to(prototype.prior.GAME / folder).as_posix(): p
                 for p in (prototype.prior.GAME / folder).rglob('*.txt')}
    effective.update({p.relative_to(prototype.ROOT / folder).as_posix(): p
                      for p in (prototype.ROOT / folder).rglob('*.txt')})
    return sorted({node.key for path in effective.values()
        for node in cw.parse(path.read_text(encoding='utf-8-sig')) if re.fullmatch(pattern, node.key)})


def render():
    tags = definitions('common/country_definitions', r'[A-Z0-9]{3}')
    regions = definitions('map_data/state_regions', r'STATE_[A-Z0-9_]+')
    assert 'FRA' in tags and 'PRU' in tags and 'STATE_ILE_DE_FRANCE' in regions
    lines = ['\ufeff# Generated by tools/vic3_bridge_identity.py from effective definitions.',
        '# Historical wire keys country_name/state_name now carry explicit ID labels.',
        '# State scope. Region key + owner TAG distinguish shared StateRegions.',
        '# No inferred bitmap RGB, no runtime State instance ID, no GUI functions.',
        'aor1776_bridge_export_identity = {', '\towner = {']
    lines.extend(f'\t\tif = {{ limit = {{ exists = c:{tag} this = c:{tag} }} debug_log = "AOR1776_BRIDGE_V1|country_name=TAG:{tag}" }}' for tag in tags)
    lines.append('\t}')
    lines.extend(f'\tif = {{ limit = {{ state_region = s:{region} }} debug_log = "AOR1776_BRIDGE_V1|state_name=REGION:{region}" }}' for region in regions)
    lines += ['}', '']
    return '\n'.join(lines), {'country_tags': len(tags), 'region_keys': len(regions)}


if __name__ == '__main__':
    text, counts = render()
    if sys.argv[1:] == ['--patch']:
        relative = (prototype.SOURCE / TARGET).relative_to(prototype.ROOT).as_posix()
        assert not (prototype.SOURCE / TARGET).exists(), 'Do not replace a modified lookup'
        print('*** Begin Patch\n*** Add File: ' + relative + '\n' + '\n'.join('+' + line for line in text.splitlines()) + '\n*** End Patch')
    elif sys.argv[1:] == ['--check']:
        assert (prototype.SOURCE / TARGET).read_text(encoding='utf-8') == text
        print(json.dumps({'status': 'PASS_EXACT_EFFECTIVE_DEFINITION_LOOKUP', **counts}))
    else:
        raise SystemExit('Use --patch or --check')
